fn last_use_update(c: &mut Criterion) {
    let shell = cargo::core::Shell::new();
    let homedir = cargo_home();
    if !homedir.exists() {
        fs::create_dir_all(&homedir).unwrap();
    }
    let f = homedir.join(".last-use"); // TODO
    if f.exists() {
        fs::remove_file(f).unwrap();
    }
    let sample = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join(LAST_USE_SAMPLE);
    fs::copy(sample, homedir.join(".last-use")).unwrap();
    let cwd = homedir.clone();
    let config = Config::new(shell, cwd, homedir);
    let _lock = config.acquire_package_cache_lock().unwrap();
    let mut last_use = LastUse::load(&config).unwrap();

    let crates_io = String::from("github.com-1ecc6299db9ec823");

    c.bench_function("last_use_update", |b|
        b.iter(|| {
            for name in RANDOM_SAMPLE {
                last_use.mark_used(LastUseKind::RegistryIndex, crates_io.clone());
                last_use.mark_used(LastUseKind::RegistryCrate(crates_io.clone()), format!("{}.crate",name));
                last_use.mark_used(LastUseKind::RegistrySrc(crates_io.clone()), name.to_string());
            }
            last_use.save(&config).unwrap();
        }
    ));
}

criterion_group!(benches, last_use_load, last_use_save, last_use_update);
criterion_main!(benches);
