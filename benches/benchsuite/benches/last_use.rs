use std::path::{Path, PathBuf};
use criterion::{criterion_group, criterion_main, Criterion};
use cargo::core::{LastUse, LastUseKind};
use cargo::util::Config;
use std::fs;

const LAST_USE_SAMPLE: &str = "last-use/last-use-sample-sqlite5";

fn root() -> PathBuf {
    let mut p = PathBuf::from(env!("CARGO_TARGET_TMPDIR"));
    p.push("bench");
    p
}

fn cargo_home() -> PathBuf {
    let mut p = root();
    p.push("chome");
    p
}

fn last_use_load(c: &mut Criterion) {
    let shell = cargo::core::Shell::new();
    let homedir = cargo_home();
    if !homedir.exists() {
        fs::create_dir_all(&homedir).unwrap();
    }
    let f = homedir.join(".last-use"); // TODO
    if f.exists() {
        fs::remove_file(f).unwrap();
    }
    let sample = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join(LAST_USE_SAMPLE);
    fs::copy(sample, homedir.join(".last-use")).unwrap();
    let cwd = homedir.clone();
    let config = Config::new(shell, cwd, homedir);
    let _lock = config.acquire_package_cache_lock().unwrap();
    c.bench_function("last_use_load", |b|
        b.iter(|| {
            LastUse::load(&config).unwrap();
        }
    ));
}

